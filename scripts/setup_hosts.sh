#!/usr/bin/env bash
# Usage: sudo bash scripts/setup_hosts.sh <node-number 1..4>
# Sets the hostname and maps node1..node4 to their ZeroTier IPs in /etc/hosts.
set -euo pipefail
N="${1:?give node number 1-4}"
DIR="$(cd "$(dirname "$0")/.." && pwd)"; source "$DIR/cluster.env"
for v in NODE1_IP NODE2_IP NODE3_IP NODE4_IP; do
  [[ "${!v}" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || {
    echo "ERROR: $v='${!v}' in $DIR/cluster.env is not a real IP."
    echo "Clone the team repo instead:  git clone https://github.com/Aryan-20-2006/Distributed-search-engine.git ~/dse"
    exit 1; }
done

if grep -qi microsoft /proc/version; then
  # WSL: the hostname and /etc/hosts are regenerated by WSL on every start unless
  # /etc/wsl.conf says otherwise. Merge our settings into it (other settings are kept).
  python3 - "$N" <<'PY'
import configparser, sys
p = "/etc/wsl.conf"
c = configparser.ConfigParser(); c.optionxform = str; c.read(p)
for sec, kv in {"boot": {"systemd": "true"},
                "network": {"hostname": f"node{sys.argv[1]}", "generateHosts": "false"}}.items():
    if not c.has_section(sec): c.add_section(sec)
    for k, v in kv.items(): c.set(sec, k, v)
with open(p, "w") as f: c.write(f)
PY
  hostname "node$N" 2>/dev/null || true
  WSL_RESTART_NEEDED=1
  echo "== WSL detected: wrote /etc/wsl.conf =="; cat /etc/wsl.conf
else
  hostnamectl set-hostname "node$N"
fi

# THE classic Hadoop bug: Ubuntu maps the hostname to 127.0.1.1, so the NameNode
# binds to loopback and DataNodes can't reach it. Remove that line.
sed -i '/^127\.0\.1\.1/d' /etc/hosts
sed -i '/ node[1-4]$/d' /etc/hosts      # drop any old node entries (re-runnable)

sed -e "s/__NODE1_IP__/$NODE1_IP/" -e "s/__NODE2_IP__/$NODE2_IP/" \
    -e "s/__NODE3_IP__/$NODE3_IP/" -e "s/__NODE4_IP__/$NODE4_IP/" \
    "$DIR/conf/hosts.snippet" | grep -v '^#' >> /etc/hosts

# cloud-init images (Multipass, cloud VMs) regenerate /etc/hosts and the hostname on
# every boot. Put our entries into its template and keep our hostname.
T=/etc/cloud/templates/hosts.debian.tmpl
if [ -f "$T" ]; then
  sed -i '/ node[1-4]$/d' "$T"
  grep -E ' node[1-4]$' /etc/hosts >> "$T"
  mkdir -p /etc/cloud/cloud.cfg.d
  printf 'preserve_hostname: true\n' > /etc/cloud/cloud.cfg.d/99-dse.cfg
  echo "== cloud-init detected: node1..node4 added to $T (survives reboot) =="
fi

echo "== /etc/hosts now =="; cat /etc/hosts
for h in node1 node2 node3 node4; do
  ping -c1 -W2 "$h" >/dev/null && echo "  $h reachable" || echo "  $h NOT reachable (is it joined + authorized in ZeroTier?)"
done
if [ -n "${WSL_RESTART_NEEDED:-}" ]; then
  echo
  echo ">> WSL: restart WSL once so the hostname sticks. In Windows PowerShell run:  wsl --shutdown"
  echo "   then open Ubuntu again and check that 'hostname' prints node$N."
fi
